import subprocess
from pathlib import Path

import pytest

from dsipa import layerB_data, layerB_model, layerB_qc


def _init_repo(path: Path) -> None:
    subprocess.run(["git", "init"], cwd=path, check=True, capture_output=True)
    subprocess.run(
        ["git", "config", "user.email", "test@example.org"],
        cwd=path,
        check=True,
    )
    subprocess.run(
        ["git", "config", "user.name", "DSIPA Test"],
        cwd=path,
        check=True,
    )
    (path / "README.md").write_text("baseline\n", encoding="utf-8")
    subprocess.run(["git", "add", "README.md"], cwd=path, check=True)
    subprocess.run(
        ["git", "commit", "-m", "baseline"],
        cwd=path,
        check=True,
        capture_output=True,
    )


@pytest.mark.parametrize(
    ("module", "dirty_path"),
    [
        (layerB_data, "analysis/reports/layerB_data_qc.md"),
        (layerB_qc, "analysis/reports/layerB_data_qc.md"),
        (layerB_model, "analysis/reports/layerB_qc_extended.md"),
    ],
    ids=["data", "qc", "model"],
)
def test_direct_entrypoint_rejects_dirty_tree_before_work(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    module,
    dirty_path: str,
) -> None:
    _init_repo(tmp_path)
    path = tmp_path / dirty_path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("generated by an earlier stage\n", encoding="utf-8")
    monkeypatch.setattr(module, "find_repo_root", lambda: tmp_path)

    with pytest.raises(SystemExit, match="unexplained changes before output generation"):
        module.main([])
